create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  match_id text not null,
  match_name text not null,
  match_date text not null,
  tickets integer not null check (tickets > 0),
  stand text not null,
  position text not null,
  venue text not null,
  place text not null,
  price_per_ticket integer not null,
  amount bigint not null,
  ticket_code text not null,
  history_token uuid not null,
  status text not null default 'Confirmed',
  created_at timestamptz not null default now()
);

alter table public.bookings
  add column if not exists email text,
  add column if not exists phone text,
  add column if not exists match_id text,
  add column if not exists match_name text,
  add column if not exists match_date text,
  add column if not exists position text,
  add column if not exists price_per_ticket integer,
  add column if not exists amount bigint,
  add column if not exists ticket_code text,
  add column if not exists history_token uuid,
  add column if not exists status text not null default 'Confirmed';

create unique index if not exists bookings_ticket_code_unique_idx
  on public.bookings (ticket_code)
  where ticket_code is not null;

create unique index if not exists bookings_history_token_unique_idx
  on public.bookings (history_token)
  where history_token is not null;

alter table public.bookings enable row level security;
revoke all on table public.bookings from public, anon, authenticated;
grant usage on schema public to anon;

create or replace function public.create_guest_booking(
  p_history_token uuid,
  p_name text,
  p_email text,
  p_phone text,
  p_match_id text,
  p_tickets integer,
  p_stand text,
  p_position text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_match_name text;
  v_match_date text;
  v_venue text;
  v_place text;
  v_price integer;
  v_booking public.bookings%rowtype;
begin
  if p_history_token is null then
    raise exception 'A booking access token is required.';
  end if;
  if length(btrim(coalesce(p_name, ''))) < 2 or length(btrim(p_name)) > 100 then
    raise exception 'Enter a name between 2 and 100 characters.';
  end if;
  if p_email is null
    or p_email !~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
    or length(p_email) > 254 then
    raise exception 'Enter a valid email address.';
  end if;
  if length(coalesce(p_phone, '')) > 32 then
    raise exception 'Phone number is too long.';
  end if;
  if p_tickets is null or p_tickets < 1 then
    raise exception 'Ticket quantity must be at least one.';
  end if;
  if p_stand = 'General Stand' then
    v_price := 500;
  elsif p_stand = 'VIP Stand' then
    v_price := 1500;
  else
    raise exception 'Choose a valid ticket stand.';
  end if;
  if p_position is null or p_position not in (
    'Section A · Lower tier',
    'Section B · Mid tier',
    'Section C · Upper tier',
    'Section D · Corner view'
  ) then
    raise exception 'Choose a valid stadium section.';
  end if;

  if p_match_id = 'rcb-csk' then
    v_match_name := 'RCB vs CSK';
    v_match_date := '25 March 2026';
    v_venue := 'M. Chinnaswamy Stadium';
    v_place := 'M. Chinnaswamy Stadium, Bengaluru';
  elsif p_match_id = 'mi-kkr' then
    v_match_name := 'MI vs KKR';
    v_match_date := '28 March 2026';
    v_venue := 'Wankhede Stadium';
    v_place := 'Wankhede Stadium, Mumbai';
  else
    raise exception 'Choose a valid match from the fixtures.';
  end if;

  insert into public.bookings (
    name,
    email,
    phone,
    match_id,
    match_name,
    match_date,
    tickets,
    stand,
    position,
    venue,
    place,
    price_per_ticket,
    amount,
    ticket_code,
    history_token
  )
  values (
    btrim(p_name),
    btrim(p_email),
    nullif(btrim(coalesce(p_phone, '')), ''),
    p_match_id,
    v_match_name,
    v_match_date,
    p_tickets,
    p_stand,
    p_position,
    v_venue,
    v_place,
    v_price,
    v_price::bigint * p_tickets,
    'IPT-' || upper(substr(replace(pg_catalog.gen_random_uuid()::text, '-', ''), 1, 12)),
    p_history_token
  )
  returning * into v_booking;

  return to_jsonb(v_booking);
end;
$$;

create or replace function public.get_guest_bookings(p_history_tokens uuid[])
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
declare
  v_bookings jsonb;
begin
  if coalesce(cardinality(p_history_tokens), 0) > 1000 then
    raise exception 'Too many booking access tokens.';
  end if;

  select coalesce(
    jsonb_agg(to_jsonb(bookings) order by bookings.created_at desc),
    '[]'::jsonb
  )
  into v_bookings
  from public.bookings as bookings
  where bookings.history_token = any(coalesce(p_history_tokens, array[]::uuid[]));

  return v_bookings;
end;
$$;

revoke all on function public.create_guest_booking(uuid, text, text, text, text, integer, text, text)
  from public, anon, authenticated;
revoke all on function public.get_guest_bookings(uuid[])
  from public, anon, authenticated;

grant execute on function public.create_guest_booking(uuid, text, text, text, text, integer, text, text)
  to anon;
grant execute on function public.get_guest_bookings(uuid[])
  to anon;
